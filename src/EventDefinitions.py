# deletion time class
class DeletionTime:
    def __init__(
        self: Self,
        deletion_interval: int|None,
        deletion_error_max: int|df.Type.Infinite
    ) -> None:
        """Holds deletion time info

        Params:
            deletion_interval - controls how long between deletion attempts for this event
                - None means this event is not error prone (deletion is handled solely by roblox or the game activity checker)
            deletion_error_max - determines how many intervals pass before erroring trying to delete
        """

        self.deletion_interval = deletion_interval 
        self.deletion_count_max = deletion_error_max

# deletion helpers
DEL_NODE = DeletionTime(5, 40)
DEL_EYEFESTATION = DeletionTime(10, 20)
DEL_ROOM = DeletionTime(30, df.Value.Infinite)
DEL_NONE = DeletionTime(None, df.Value.Infinite)

# event option class
class EventOption:
    def __init__(
        self: Self, 
        name: str, 
        association: CategoryOptions|SoundOptions,
        deletion_settings: DeletionTime
    ) -> None:
        self.name = name
        self.association = association
        self.deletion_settings = deletion_settings

    def associtation_is_categoric(self: Self): 
        return isinstance(self.association, CategoryOptions)

