# game start helpers
recently_began: bool = False
def reset_game_recently_started() -> None:
    global recently_began
    recently_began = False
    LoggerRegistry.log_at(LogChannel.SettingChange, "set game recently started to false")

# eyefestation helpers
eyefestation_enrage_level: int = 1
eyefestation_music_recently_played: bool = False
def reset_eyefestation_music_recently_played() -> None: 
    global eyefestation_music_recently_played
    eyefestation_music_recently_played = False
    LoggerRegistry.log_at(LogChannel.SettingChange, "set eyefestation music to false")
eyefestation_talking_recently_played: bool = False
